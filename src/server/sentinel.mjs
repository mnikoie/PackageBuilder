/**
 * تشخیصِ «فرمان تمام شد» از خروجیِ ترمینال.
 *
 * ---- مسئله ----
 * ترمینال یک جریانِ بی‌شکل است؛ نمی‌گوید «فرمانِ شما تمام شد». راهِ عملی این
 * است که به دنبالِ فرمانِ کاربر یک نشانه (سنتینل) بچسبانیم:
 *
 *     <فرمان>; if ($?) { Write-Host "##STEP_OK:<id>##" } else { ... }
 *
 * بعد در خروجی دنبالِ آن نشانه بگردیم، از نمایش حذفش کنیم، و به بالادست
 * خبر بدهیم که آن مرحله تمام شد.
 *
 * ---- تله‌ای که نسخهٔ قبلی در آن افتاد ----
 * خروجیِ PTY تکه‌تکه می‌رسد و مرزِ تکه‌ها هیچ ربطی به مرزِ کلمات ندارد. نشانه
 * می‌تواند وسطش بشکند:
 *
 *     تکهٔ ۱: "...done\r\n##STEP_"
 *     تکهٔ ۲: "OK:abc##\r\n"
 *
 * اگر هر تکه را جدا بررسی کنی، هیچ‌کدام نشانهٔ کامل ندارند — پس هرگز خبرِ
 * پایان نمی‌رسد و وضعیت **برای همیشه** روی «در حالِ اجرا» گیر می‌کند. این
 * باگ در نسخهٔ قبلی ماه‌ها پنهان بود و فقط با فرمان‌های کندِ Docker بیرون زد.
 *
 * ---- راه‌حل ----
 * یک بافر نگه می‌داریم. هر بار:
 *   ۱. همهٔ نشانه‌های **کامل** را برمی‌داریم و خبرشان را می‌دهیم.
 *   ۲. اگر تهِ بافر چیزی هست که *می‌تواند* آغازِ یک نشانهٔ ناتمام باشد، همان
 *      را نگه می‌داریم و بقیه را برای نمایش می‌فرستیم.
 *
 * این فایل عمداً **خالص** است: نه PTY، نه سوکت، نه تایمر. فقط رشته می‌گیرد و
 * رشته می‌دهد — تا بشود بی‌رحمانه تستش کرد، از جمله حالتی که خروجی حرف‌به‌حرف
 * برسد.
 */

const HEADS = ["##STEP_OK:", "##STEP_FAIL:"];
const ID_CHARS = /^[A-Za-z0-9_-]*$/;

/** بلندترین نشانهٔ ممکن — برای اینکه بافرِ نگه‌داشته‌شده بی‌مرز رشد نکند. */
const MAX_ID = 64;
export const MAX_SENTINEL_LENGTH = "##STEP_FAIL:".length + MAX_ID + "##".length;

const FULL = /##STEP_(OK|FAIL):([A-Za-z0-9_-]{1,64})##/g;

/**
 * آیا این رشته می‌تواند آغازِ یک نشانهٔ ناتمام باشد؟
 * (یعنی: ارزش دارد که نگهش داریم و منتظرِ بقیه‌اش بمانیم؟)
 */
export function couldStartSentinel(s) {
  if (!s) return false;
  if (s.length > MAX_SENTINEL_LENGTH) return false;
  for (const head of HEADS) {
    // در حالِ تایپ‌شدنِ خودِ سرِ نشانه: "#", "##", "##S", ... "##STEP_FAIL:"
    if (head.startsWith(s)) return true;
    // سر کامل آمده، در حالِ آمدنِ شناسه و «##» پایانی
    if (s.startsWith(head)) {
      const rest = s.slice(head.length);
      if (rest.length > MAX_ID + 2) return false;
      // شناسه، یا شناسه + یک «#» تنها (نیمهٔ «##» پایانی)
      const body = rest.endsWith("#") ? rest.slice(0, -1) : rest;
      return ID_CHARS.test(body);
    }
  }
  return false;
}

/**
 * سازندهٔ تجزیه‌گر.
 *
 * @param {(result: { id: string, ok: boolean }) => void} onResult
 *        هر بار که یک نشانهٔ کامل دیده شد صدا زده می‌شود.
 * @returns {{
 *   push: (chunk: string) => string,   // متنِ آماده‌ی نمایش
 *   flush: () => string,               // هر چه نگه داشته‌ایم را رها کن
 *   pending: () => string,             // فقط برای تست/بازرسی
 * }}
 */
export function createSentinelParser(onResult = () => {}) {
  let buffer = "";

  function push(chunk) {
    buffer += chunk;

    // ۱) نشانه‌های کامل را بردار و خبر بده
    buffer = buffer.replace(FULL, (_match, kind, id) => {
      onResult({ id, ok: kind === "OK" });
      return "";
    });

    // ۲) دنبالِ کوچک‌ترین پسوندی بگرد که می‌تواند نشانهٔ ناتمام باشد.
    //    از انتها به عقب می‌گردیم و فقط تا اندازهٔ بلندترین نشانهٔ ممکن —
    //    پس هزینه‌اش ثابت است، نه وابسته به حجمِ خروجی.
    const from = Math.max(0, buffer.length - MAX_SENTINEL_LENGTH);
    let holdAt = -1;
    for (let i = buffer.length - 1; i >= from; i--) {
      if (buffer[i] !== "#") continue;
      if (couldStartSentinel(buffer.slice(i))) holdAt = i;
    }

    if (holdAt === -1) {
      const out = buffer;
      buffer = "";
      return out;
    }

    const out = buffer.slice(0, holdAt);
    buffer = buffer.slice(holdAt);
    return out;
  }

  function flush() {
    const out = buffer;
    buffer = "";
    return out;
  }

  return { push, flush, pending: () => buffer };
}

/**
 * یک‌بار در آغازِ هر پوسته اجرا می‌شود و تابعِ اعلامِ پایان را تعریف می‌کند.
 *
 * ---- تلهٔ دوم: پژواکِ فرمان ----
 * پاورشلِ تعاملی خودِ خطِ فرمان را هم پژواک می‌کند. اگر نشانه عیناً در متنِ
 * فرمان باشد، تجزیه‌گر آن را **در پژواک** می‌بیند — قبل از اینکه فرمان اجرا
 * شود. و چون پژواک هر دو شاخه (OK و FAIL) را دارد، اولین خبر «موفق» است:
 * یعنی فرمانی که شکست خورده، موفق گزارش می‌شود. (اندازه‌گیریِ واقعی: سه خبر
 * برای یک فرمان — true، false، true.)
 *
 * راه‌حل: خودِ نشانه در زمانِ اجرا و **داخلِ این تابع** سرِهم می‌شود. پس خطِ
 * فرمان فقط `__pbEnd <id> $?` دارد — نه «STEP_OK»، نه «##». پژواک از اساس
 * بی‌خطر می‌شود، و ضمناً خیلی خواناتر است تا یک if/else طولانی روی هر فرمان.
 */
/**
 * ---- تلهٔ سوم: `$?` برای فرمان‌های بیرونی دروغ می‌گوید ----
 * در پاورشل، اگر یک فرمانِ بیرونی چیزی روی stderr بنویسد، `$?` می‌شود
 * `false` — حتی اگر کدِ خروجش صفر و کارش کاملاً موفق باشد. و pnpm نوارِ
 * پیشرفتش را روی stderr می‌نویسد.
 *
 * نتیجهٔ واقعی: `pnpm add -Dw nx` پکیج را **درست نصب می‌کرد** ولی ابزار
 * «شکست خورد» گزارش می‌داد. (آینهٔ باگِ پژواک: آن موفقیتِ دروغ می‌داد، این
 * شکستِ دروغ.)
 *
 * راه‌حل — تفکیکِ فرمانِ بیرونی از cmdlet:
 * قبلِ اجرا `$LASTEXITCODE` را روی یک عددِ نشانه (۹۹۹) می‌گذاریم.
 *   • اگر بعدش همان ۹۹۹ ماند → فرمان یک cmdlet بود و کدِ خروج ندارد، پس
 *     `$?` معیارِ درست است.
 *   • اگر عوض شد → فرمانِ بیرونی بود، و تنها معیارِ درست کدِ خروج است.
 */
const SENTINEL_PROBE = 999;

export const SETUP_COMMAND =
  "function __pbEnd { param($id, $success, $code) " +
  `$ok = if ($code -eq ${SENTINEL_PROBE}) { $success } else { $code -eq 0 }; ` +
  'Write-Host ("#"*2 + "STEP_" + $(if ($ok) { "OK" } else { "FAIL" }) + ":" + $id + "#"*2) }';

/**
 * ساختنِ فرمانی که خودش پایانش را اعلام می‌کند.
 *
 * با «;» به همان خط چسبانده می‌شود، نه خطِ جدا — وگرنه یک خطِ اضافه روی
 * پرامپت می‌افتد و کاربر فکر می‌کند چیزی خراب شده.
 *
 * `$?` همان‌جا و بی‌درنگ بعد از فرمان ارزیابی می‌شود، پس وضعیتِ خودِ همان
 * فرمان را می‌گیرد، نه چیزِ دیگری.
 */
export function withSentinel(command, stepId) {
  if (!/^[A-Za-z0-9_-]{1,64}$/.test(stepId)) {
    throw new Error(`شناسهٔ مرحله نامعتبر است: ${stepId}`);
  }
  // عددِ نشانه قبل، و هر دو معیار بعد — تا __pbEnd بتواند تشخیص بدهد فرمان
  // بیرونی بوده یا cmdlet. شرحش بالای SETUP_COMMAND.
  //
  // ---- تلهٔ چهارم: خطای قطع‌کننده ----
  // یک خطای terminating در پاورشل (مثلاً `-ErrorAction Stop`) بقیهٔ همان خط را
  // رد می‌کند — پس `__pbEnd` هرگز اجرا نمی‌شد و وضعیت **برای همیشه** روی
  // «در حالِ اجرا» گیر می‌کرد. با try/catch تضمین می‌کنیم خبر در هر دو حالت
  // برسد؛ شکستِ اعلام‌شده بی‌نهایت بهتر از سکوت است.
  return (
    `$global:LASTEXITCODE = ${SENTINEL_PROBE}; ` +
    `try { ${command}; __pbEnd ${stepId} $? $LASTEXITCODE } ` +
    `catch { __pbEnd ${stepId} $false 1 }`
  );
}
